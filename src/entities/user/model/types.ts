/**
 * Профиль пользователя в форме, которую отдаёт бэкенд.
 */
export interface User {
    /** Публичный идентификатор пользователя (UUID). Внутренние числовые id
     *  наружу не отдаются — для совместной корзины и долей счёта используется
     *  именно этот идентификатор. */
    public_id: string;
    /** Отображаемое имя. */
    name: string;
    /** Email-адрес. */
    email: string;
    /** Ссылка на аватар. */
    avatar_url: string;
    /** Длина текущей серии заказов в неделях (геймификация). */
    streak_weeks?: number;
}

/**
 * Состояние асинхронной загрузки профиля.
 *
 * - `idle` - запросов не выполняется;
 * - `loading` - идёт загрузка;
 * - `error` - последний запрос завершился ошибкой.
 */
export type UserStatus = 'idle' | 'loading' | 'error';

/**
 * Состояние стора пользователя.
 */
export interface UserState {
    /** Текущий пользователь или `null`, если он не авторизован. */
    user: User | null;
    /** Состояние асинхронных операций. */
    status: UserStatus;
    /**
     * Завершилась ли первая проверка авторизации (`loadCurrent`). До этого
     * момента UI не должен показывать ни гостевые, ни пользовательские
     * элементы, иначе при загрузке мигают кнопки «Войти/Регистрация».
     */
    authResolved: boolean;
}
