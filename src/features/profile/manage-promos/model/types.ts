/**
 * Промокод в карточке профиля. Тип готов к замене на бэкенд-сущность:
 * совпадает по полям с тем, что показывает макет (код, описание, условие,
 * срок действия, опционально тег «истекает»).
 */
export interface Promo {
    /** Уникальный идентификатор; пока используется как `key` в списке. */
    id: string;
    /** Сам промокод, отображается в плашке капсом. */
    code: string;
    /** Краткое описание выгоды («Скидка 30% на пиццу»). */
    title: string;
    /** Условие применения: ресторан, минимальный чек и т. п. */
    condition: string;
    /** Срок действия в человекочитаемом виде. */
    expiresAt: string;
    /** Если true, плашка показывается «горящим» вариантом (через дня-два протухнет). */
    expiringSoon?: boolean;
    /** Альтернативный текст срока для горящего промокода («Истекает через 2 дня»). */
    expiringSoonText?: string;
}
